let marks = 85;

if (marks >= 90) {
    console.log("Grade A");
} else if (marks >= 80) {
    console.log("Grade B");
} else if (marks >= 60) {
    console.log("Grade C");
} else if (marks >= 55) {
    console.log("Grade D");
} else if (marks >= 33) {
    console.log("Grade E - Pass");
} else {
    console.log("Fail");
}